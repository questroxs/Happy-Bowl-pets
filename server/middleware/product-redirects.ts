export default function productRedirects(
  event: { url: URL },
  next: () => unknown,
) {
  const path = event.url.pathname.replace(/\/+$/, "") || "/";
  const target = REDIRECTS[path];
  if (!target) return next();
  return new Response(null, {
    status: 301,
    headers: { Location: target + event.url.search },
  });
}
